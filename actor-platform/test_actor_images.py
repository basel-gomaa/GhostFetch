#!/usr/bin/env python3
"""Every image that pins Playwright pins it ONCE (offline, reads files only).

    python3 test_actor_images.py

An image built FROM mcr.microsoft.com/playwright/python:vX ships the browsers
for version X and nothing else. If the image's requirements then install a
different playwright package, pip replaces the image's own copy and every
browser launch fails with "Executable doesn't exist at /ms-playwright/...".

That happened for real: Dependabot bumped the base image of three Actors from
v1.49.1 to v1.64.1, CI passed (it never builds Actor images), and the next
LinkedIn run died at launch because requirements.txt still said 1.49.1. This
test is what makes such a bump fail CI until the pin follows it.
"""

from __future__ import annotations

import re
import sys
import traceback
from pathlib import Path

ROOT = Path(__file__).resolve().parent
IMAGE_RE = re.compile(r"^FROM\s+mcr\.microsoft\.com/playwright/python:v(\d+\.\d+\.\d+)", re.M)
PIN_RE = re.compile(r"\bplaywright==(\d+\.\d+\.\d+)")

TESTS = []


def test(fn):
    TESTS.append(fn)
    return fn


def image_dirs() -> list[Path]:
    dirs = sorted(p for p in (ROOT / "actors").iterdir() if (p / "Dockerfile").is_file())
    return dirs


def pins(directory: Path) -> set[str]:
    """Every playwright version the image installs: its requirements file(s) and
    any `pip install playwright==X` written into the Dockerfile itself."""
    found: set[str] = set()
    for path in [directory / "Dockerfile", *directory.glob("requirements*.txt"),
                 *directory.glob("requirements*.in")]:
        text = "\n".join(line.split("#", 1)[0] for line in path.read_text().splitlines())
        found.update(PIN_RE.findall(text))
    return found


@test
def test_an_image_on_the_playwright_base_installs_that_same_playwright():
    checked = 0
    for directory in image_dirs():
        base = IMAGE_RE.search((directory / "Dockerfile").read_text())
        if not base:
            continue
        checked += 1
        installed = pins(directory)
        assert installed <= {base.group(1)}, (
            f"{directory.relative_to(ROOT)}: base image is playwright v{base.group(1)} "
            f"but it installs playwright {sorted(installed)} -- the browsers in the "
            f"image will not match; set playwright=={base.group(1)}")
    assert checked >= 3, f"expected the browser Actors on the playwright base, found {checked}"


@test
def test_an_image_pins_playwright_at_most_once():
    for directory in image_dirs():
        installed = pins(directory)
        assert len(installed) <= 1, (
            f"{directory.relative_to(ROOT)} installs two playwright versions: {sorted(installed)}")


# ------------------------------------------------- every image installs a lock
#
# An image used to install loose ranges (`anthropic>=0.40`), and the login
# browser's pins were written into its Dockerfile, so what an image held was
# decided at build time and seen by no audit: on 30 October that was starlette
# 0.41.3 (7 advisories) in one image. Now each image has requirements.in (what
# it depends on) and requirements.txt (its hashed lock, made by
# scripts/image_locks.py), and installs only the lock, with --require-hashes.

LOCK_PIN = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==(\S+)")
IN_REQ = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)(\[[^\]]*\])?\s*(.*)$")
PIP_INSTALL = re.compile(r"\bpip\s+install\b(?P<args>[^&;\n]*)")


def normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def lock_entries(path: Path) -> dict[str, tuple[str, list[str]]]:
    """{name: (version, hashes)} from a pip-compile lock, continuations joined."""
    entries: dict[str, tuple[str, list[str]]] = {}
    logical = re.sub(r"\\\n", " ", path.read_text())
    for line in logical.splitlines():
        line = line.split(" #", 1)[0].strip()
        m = LOCK_PIN.match(line)
        if m:
            entries[normalize(m.group(1))] = (m.group(2), re.findall(r"--hash=sha256:[0-9a-f]{64}", line))
    return entries


def dockerfile_logical(directory: Path) -> str:
    return re.sub(r"\\\n", " ", (directory / "Dockerfile").read_text())


@test
def test_every_image_has_a_requirements_in_and_a_hashed_lock():
    for directory in image_dirs():
        name = directory.relative_to(ROOT)
        assert (directory / "requirements.in").is_file(), f"{name}: no requirements.in"
        lock = directory / "requirements.txt"
        assert lock.is_file(), f"{name}: no requirements.txt -- python3 scripts/image_locks.py lock"
        assert "autogenerated by pip-compile" in lock.read_text(), (
            f"{name}/requirements.txt is not pip-compile's output; re-lock it with "
            f"scripts/image_locks.py (Dependabot only updates a lock it recognises)")
        assert "--generate-hashes" in lock.read_text(), f"{name}: lock compiled without hashes"
        for pkg, (version, hashes) in lock_entries(lock).items():
            assert hashes, f"{name}/requirements.txt: {pkg}=={version} has no --hash"


@test
def test_every_lock_covers_what_its_requirements_in_asks_for():
    """A requirements.in edited without re-locking is a lock that installs the old set."""
    for directory in image_dirs():
        name = directory.relative_to(ROOT)
        entries = lock_entries(directory / "requirements.txt")
        for raw in (directory / "requirements.in").read_text().splitlines():
            line = raw.split("#", 1)[0].strip()
            if not line:
                continue
            m = IN_REQ.match(line)
            assert m, f"{name}/requirements.in: cannot read {line!r}"
            pkg, spec = normalize(m.group(1)), m.group(3).replace(" ", "")
            image = directory.name
            assert pkg in entries, (
                f"{name}: requirements.in asks for {pkg} but the lock has none -- "
                f"python3 scripts/image_locks.py lock {image}")
            if spec.startswith("==") and "," not in spec:
                assert entries[pkg][0] == spec[2:], (
                    f"{name}: requirements.in pins {pkg}{spec} but the lock has "
                    f"{entries[pkg][0]} -- re-lock it")


@test
def test_every_image_installs_only_its_lock_with_hashes():
    for directory in image_dirs():
        name = directory.relative_to(ROOT)
        installs = [m.group("args") for m in PIP_INSTALL.finditer(dockerfile_logical(directory))]
        assert installs, f"{name}/Dockerfile installs no requirements at all"
        for args in installs:
            assert "--require-hashes" in args and re.search(r"-r\s+\S*requirements\.txt\b", args), (
                f"{name}/Dockerfile: `pip install{args}` -- an image installs only its "
                f"lock, as `pip install --require-hashes --no-deps -r requirements.txt`; "
                f"a package named here is invisible to Dependabot and every audit")


PIP_CACHE_MOUNT = "--mount=type=cache,target=/root/.cache/pip"


@test
def test_every_install_keeps_its_downloads_between_builds():
    """Without the cache mount, any change to the install layer's inputs
    re-downloads every package. On 2 November that was the whole Facebook lock
    again, at ~25 kB/s through Docker's bridge, while a run sat PENDING behind
    the build. The lock was byte-identical to the last build's; only its file
    mode differed, and BuildKit's cache key includes the mode."""
    for directory in image_dirs():
        name = directory.relative_to(ROOT)
        for line in dockerfile_logical(directory).splitlines():
            if not PIP_INSTALL.search(line) or "-r" not in line:
                continue
            assert PIP_CACHE_MOUNT in line, (
                f"{name}/Dockerfile: `{line.strip()[:80]}...` -- install with "
                f"`RUN {PIP_CACHE_MOUNT} pip install ...` so a rebuild reuses downloads")
            assert "--no-cache-dir" not in line, (
                f"{name}/Dockerfile: --no-cache-dir defeats the cache mount (and the "
                f"mount already keeps the cache out of the image)")


@test
def test_an_image_on_the_playwright_base_removes_the_bases_own_packages():
    """The Playwright base pip-installs virtualenv and its dependencies, which
    nothing runs and no lock lists (filelock + virtualenv: 24 advisories on
    30 October). They must go before the lock is installed."""
    for directory in image_dirs():
        text = dockerfile_logical(directory)
        if not IMAGE_RE.search((directory / "Dockerfile").read_text()):
            continue
        uninstall = text.find("pip uninstall")
        install = PIP_INSTALL.search(text)
        assert uninstall != -1, f"{directory.relative_to(ROOT)}: keeps the base image's packages"
        assert install and uninstall < install.start(), (
            f"{directory.relative_to(ROOT)}: removes the base's packages after installing the lock")


@test
def test_dependabot_watches_every_images_lock():
    config = (ROOT.parent / ".github" / "dependabot.yml").read_text()
    for directory in image_dirs():
        path = f'"/{directory.relative_to(ROOT.parent).as_posix()}"'
        assert path in config, (
            f".github/dependabot.yml: no pip entry lists {path}, so nothing will "
            f"ever propose an update to that image's lock")


def main() -> int:
    failed = 0
    print(f"running {len(TESTS)} image tests\n")
    for fn in TESTS:
        name = fn.__name__.removeprefix("test_")
        try:
            fn()
            print(f"  ok    {name}")
        except Exception as exc:  # noqa: BLE001
            failed += 1
            print(f"  FAIL  {name}: {type(exc).__name__}: {exc}")
            traceback.print_exc()
    print(f"\n{failed} FAILED" if failed else "\nall passed")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
